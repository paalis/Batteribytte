#!/usr/bin/env python3
"""Batteribytte · turn the chosen sounds (tools/sfx/selection.json) into the files the page plays (step 6).

For each chosen sound:
  - one-shots: cut the silence before (keep 3 ms) and after (keep 40 ms, then a 30 ms fade); a 2 ms fade in
  - loops: the whole take, the last 40 ms crossfaded (equal power) into the first, so the end runs into the start;
    then the first 0.1 s appended again as padding, so an encoder's tail padding is never reached (the page loops
    over [0, loop length) only)
  - level: the body brought to the loudness its role needs in the mix, never above -1 dBFS peak
  - stereo where width matters (the pop, spray, fizz, crush, the big moments, the machine's air), mono otherwise
  - written as assets/sfx/<id>.ogg (Vorbis) and assets/sfx/<id>.m4a (AAC, for Safari), and the list the page
    needs (length, loop length, channels) as src/pant/sfx-manifest.js

  python3 tools/sfx/prepare.py
  python3 tools/sfx/prepare.py drink     # just these
"""
import json, subprocess, pathlib
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[2]
SR = 44100
OUT = ROOT / 'assets/sfx'
STEREO = {'pop', 'spray', 'fizz', 'crush', 'full', 'whoosh', 'charge', 'hum', 'rumble', 'room'}
LOOPS = {'fizz', 'charge', 'hum', 'rollers', 'rumble', 'room'}
# the body's RMS target in dBFS, by role in the mix (the page adds its own per-play gain on top)
TARGET = {
    'pop': -15, 'spray': -18, 'fizz': -24, 'charge': -22, 'full': -16, 'powerDown': -20, 'hum': -30, 'crush': -14,
    'reject': -17, 'accept': -19, 'scanBeep': -22, 'suck': -18, 'gulp': -17, 'rollers': -26, 'lock': -18, 'click': -19,
    'printer': -21, 'rumble': -22, 'rattle': -18, 'clank': -18, 'thud': -16, 'drop': -20, 'whoosh': -20, 'tick': -22,
    'grab': -24, 'ui': -26, 'room': -36, 'drink': -19,
}

def load(path, ch):
    r = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(path), '-f', 'f32le', '-ac', str(ch), '-ar', str(SR), '-'], capture_output=True, check=True)
    return np.frombuffer(r.stdout, dtype=np.float32).reshape(-1, ch).copy()

def fade(n, up=True):
    f = 0.5 - 0.5 * np.cos(np.linspace(0, np.pi, n))
    return (f if up else f[::-1])[:, None]

def one_shot(x):
    a = np.abs(x).max(axis=1)
    thr = a.max() * 10 ** (-45 / 20)
    idx = np.nonzero(a > thr)[0]
    s = max(0, idx[0] - int(0.003 * SR)); e = min(len(x), idx[-1] + int(0.04 * SR))
    y = x[s:e].copy()
    n_in, n_out = min(len(y) // 4, int(0.002 * SR)), min(len(y) // 3, int(0.03 * SR))
    y[:n_in] *= fade(n_in); y[-n_out:] *= fade(n_out, False)
    return y, len(y)

def loop(x):
    X = int(0.04 * SR)
    y = x[:len(x) - X].copy()
    up = np.sqrt(fade(X)); down = np.sqrt(fade(X, False))          # equal power
    y[:X] = x[:X] * up + x[len(x) - X:] * down
    n = len(y)
    return np.concatenate([y, y[:int(0.1 * SR)]]), n

def level(y, target):
    a = np.abs(y).max(axis=1)
    body = y[a > a.max() * 10 ** (-40 / 20)]
    rms = np.sqrt(np.mean(body ** 2)) if len(body) else 1e-9
    g = 10 ** ((target - 20 * np.log10(rms)) / 20)
    g = min(g, 10 ** (-1 / 20) / a.max())                             # peak at most -1 dBFS
    return y * g, 20 * np.log10(g)

def write(y, ch, sid):
    raw = y.astype(np.float32).tobytes()
    base = ['ffmpeg', '-v', 'error', '-y', '-f', 'f32le', '-ar', str(SR), '-ac', str(ch), '-i', '-']
    quiet = sid == 'room'
    subprocess.run(base + ['-c:a', 'libvorbis', '-q:a', '1' if quiet else ('3' if ch == 2 else '2'), str(OUT / f'{sid}.ogg')], input=raw, check=True)
    subprocess.run(base + ['-c:a', 'aac', '-b:a', '48k' if quiet else ('96k' if ch == 2 else '64k'), '-movflags', '+faststart', str(OUT / f'{sid}.m4a')], input=raw, check=True)

def main():
    import sys
    only = set(sys.argv[1:])                                          # just these ids (the rest stay as they are)
    sel = json.loads((ROOT / 'tools/sfx/selection.json').read_text())['selections']
    old = {}
    if only:
        txt = (ROOT / 'src/pant/sfx-manifest.js').read_text()
        old = json.loads(txt[txt.index('{'):txt.rindex('}') + 1])
    OUT.mkdir(exist_ok=True)
    man, tot_o, tot_m = {}, 0, 0
    for s in sel:
        sid = s['sound']
        if not s.get('choice') or s['choice'] == 'none':
            continue
        if only and sid not in only:
            if sid in old: man[sid] = old[sid]
            continue
        ch = 2 if sid in STEREO else 1
        x = load(ROOT / s['file'], ch)
        y, n = loop(x) if sid in LOOPS else one_shot(x)
        y, gdb = level(y, TARGET[sid])
        write(y, ch, sid)
        o, m = (OUT / f'{sid}.ogg').stat().st_size, (OUT / f'{sid}.m4a').stat().st_size
        tot_o += o; tot_m += m
        man[sid] = dict(loop=sid in LOOPS, len=round(n / SR, 5), ch=ch)
        print(f'{sid:10s} {"loop" if sid in LOOPS else "    "} {n / SR:5.2f} s  {ch}ch  gain {gdb:+5.1f} dB  ogg {o / 1024:5.1f} kB  m4a {m / 1024:5.1f} kB')
    (ROOT / 'src/pant/sfx-manifest.js').write_text(
        '// generated by tools/sfx/prepare.py from tools/sfx/selection.json: the sounds the page plays\n'
        '// (len: seconds; for loops, the loop length: the files carry 0.1 s of padding after it)\n'
        f'export default {json.dumps(man, separators=(",", ":"))};\n')
    print(f'total ogg {tot_o / 1024:.0f} kB, m4a {tot_m / 1024:.0f} kB')

if __name__ == '__main__':
    main()
